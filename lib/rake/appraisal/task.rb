# frozen_string_literal: true

require "rake/tasklib"
require "appraisal"

module Rake
  module Appraisal
    # Tasks to create and check manifest file
    class Task < Rake::TaskLib
      attr_accessor :name

      def initialize(name = :appraisal)
        super()

        self.name = name

        yield self if block_given?

        namespace name do
          define_task
        end
      end

      private

      def define_task
        desc "Check appraisals"
        task :check do
          ::Appraisal::AppraisalFile.each do |appraisal|
            existing = actual_content_for(appraisal)
            expected = expected_content_for(appraisal)

            unless existing.chomp == expected.chomp
              raise "Outdated appraisal: #{appraisal.name}"
            end
          end
        end
      end

      def actual_content_for(appraisal)
        path = appraisal.gemfile_path
        raise "Appraisal has not been generated: #{appraisal.name}" unless File.exist? path

        File.read(path)
      end

      def expected_content_for(appraisal)
        signature = ::Appraisal::Customize.heading || "This file was generated by Appraisal"
        header = appraisal.send :comment_lines, signature
        body = appraisal.send :quoted_gemfile
        [header, body].join("\n\n")
      end
    end
  end
end
