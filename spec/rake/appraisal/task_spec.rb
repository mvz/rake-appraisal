# frozen_string_literal: true

RSpec.describe Rake::Appraisal::Task, type: :aruba do
  it "defines a task appraisal:check" do
    Rake.application.clear
    described_class.new
    task = Rake.application.tasks.first
    expect(task.name).to eq "appraisal:check"
  end

  describe "the generated task" do
    let(:task) do
      Rake.application.clear
      described_class.new
      Rake.application.tasks.first
    end

    before do
      write_file "Gemfile", <<~RUBY
        source "https://rubygems.org"
        gemspec
      RUBY

      write_file "Appraisals", <<~RUBY
        appraise "foo" do
          gem "foo", "~> 1.0"
        end
      RUBY
    end

    it "passes when appraisal is up-to-date" do
      write_file "gemfiles/foo.gemfile", <<~RUBY
        # This file was generated by Appraisal

        source "https://rubygems.org"

        gem "foo", "~> 1.0"

        gemspec path: "../"
      RUBY

      expect do
        in_current_directory do
          with_unbundled_env do
            task.invoke
          end
        end
      end.not_to raise_error
    end

    it "raises an error when appraisal is outdated" do
      write_file "Appraisals", <<~RUBY
        appraise "foo" do
          gem "foo", "~> 1.0"
        end
      RUBY

      write_file "gemfiles/foo.gemfile", <<~RUBY
        # This file was generated by Appraisal

        source "https://rubygems.org"

        gem "foo", "~> 0.5.0"

        gemspec path: "../"
      RUBY

      expect do
        in_current_directory { task.invoke }
      end.to raise_error RuntimeError, "Outdated appraisal: foo"
    end

    it "raises an error when appraisal does not yet exist" do
      write_file "Appraisals", <<~RUBY
        appraise "foo" do
          gem "foo", "~> 1.0"
        end
      RUBY
      expect do
        in_current_directory { task.invoke }
      end.to raise_error RuntimeError, "Appraisal has not been generated: foo"
    end
  end
end
